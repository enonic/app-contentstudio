const viewed = vi.hoisted(() => ({ content: undefined as unknown }));

vi.mock('./wizardViewedContent.utils', () => ({ buildViewedContent: () => viewed.content }));
vi.mock('../../../shared/i18n', () => ({ i18n: (key: string, ...args: string[]) => [key, ...args].join(' ') }));

const PART_KEY = 'com.enonic.app.superhero:latest-comments';
const CONTROLLER_KEY = 'com.enonic.app.superhero:default';
const UNKNOWN_PART_KEY = 'com.enonic.app.superhero:removed-part';

type PartJson = { descriptor: string; config: PropertyArrayJson[] };
type RegionJson = { name: string; components: { PartComponent?: PartJson }[] };
type PageParams = { regions: RegionJson[] | null; fragment: { PartComponent?: PartJson } | null };

function inputJson(name: string, inputType: string): object {
    return {
        formItemType: 'Input',
        name,
        inputType,
        label: name,
        occurrences: { minimum: 0, maximum: 1 },
        config: {},
        helpText: '',
    };
}

function descriptorOf(key: string, formItems: object[], regions: { name: string }[] = []): Descriptor {
    return Descriptor.fromJson({
        key,
        name: DescriptorKey.fromString(key).getName(),
        displayName: key,
        description: '',
        config: formItems,
        regions,
        autoGenerated: false,
    } as unknown as DescriptorJson);
}

const descriptors: Record<string, Descriptor> = {
    [PART_KEY]: descriptorOf(PART_KEY, [inputJson('headline', 'TextLine'), inputJson('size', 'Long')]),
    [CONTROLLER_KEY]: descriptorOf(CONTROLLER_KEY, [], [{ name: 'main' }]),
};

function stringArray(name: string, value: string): PropertyArrayJson {
    return { name, type: 'String', values: [{ v: value }] };
}

function latestCommentsPart(descriptorKey: string = PART_KEY): PartComponent {
    return new PartComponentBuilder()
        .setDescriptor(DescriptorKey.fromString(descriptorKey))
        .setConfig(PropertyTree.fromJson([stringArray('headline', 'Latest comments'), stringArray('size', '5')]))
        .build();
}

function customizedPage(part: PartComponent): Page {
    const region = Region.create().setName('main').addComponent(part).build();
    return new PageBuilder()
        .setController(DescriptorKey.fromString(CONTROLLER_KEY))
        .setRegions(Regions.create().addRegion(region).build())
        .build();
}

function createContent(page: Page | null): Content {
    const builder = new ContentBuilder();
    builder.setId('content-id');
    builder.setContentId(new ContentId('content-id'));
    builder.setName(new ContentName('post'));
    builder.setType(new ContentTypeName('com.enonic.app.superhero:post'));
    builder.setDisplayName('Post');
    builder.setData(new PropertyTree());
    builder.setPage(page);
    return builder.build();
}

async function savePage(viewedPage: Page): Promise<PageParams> {
    const persistedContent = createContent(null);
    const viewedContent = createContent(viewedPage);
    let sentParams: PageParams = null;

    vi.spyOn(CreatePageRequest.prototype, 'sendAndParse').mockImplementation(function (this: CreatePageRequest) {
        sentParams = this.getParams() as PageParams;
        return Q(viewedContent);
    });

    await saveWizardPage(persistedContent, viewedContent);

    return sentParams;
}

function partConfig(params: PageParams): PropertyArrayJson[] {
    return params.regions[0].components[0].PartComponent.config;
}

describe('saveWizardPage', () => {
    beforeAll(() => {
        registerBuiltInTypes();
    });

    beforeEach(() => {
        vi.spyOn(GetComponentDescriptorRequest.prototype, 'sendAndParse').mockImplementation(function (
            this: GetComponentDescriptorRequest,
        ) {
            const key = (this as unknown as { descriptorKey: string }).descriptorKey;
            const descriptor = descriptors[key];
            return descriptor ? Q(descriptor) : Q.reject<Descriptor>(new Error(`No descriptor ${key}`));
        });
    });

    afterEach(() => {
        vi.restoreAllMocks();
    });

    it('should send component config values typed by the descriptor inputs when a customized page is saved', async () => {
        const params = await savePage(customizedPage(latestCommentsPart()));

        expect(partConfig(params)).toEqual([
            { name: 'headline', type: 'String', values: [{ v: 'Latest comments' }] },
            { name: 'size', type: 'Long', values: [{ v: 5 }] },
        ]);
    });

    it('should save a template-only page without regions', async () => {
        const params = await savePage(new PageBuilder().setTemplate(PageTemplateKey.fromString('template-id')).build());

        expect(params).not.toBeNull();
        expect(params.regions).toBeNull();
        expect(params.fragment).toBeNull();
    });

    it('should normalize the config of a standalone fragment', async () => {
        const params = await savePage(new PageBuilder().setFragment(latestCommentsPart()).build());

        expect(params.regions).toBeNull();
        expect(params.fragment.PartComponent.config).toEqual([
            { name: 'headline', type: 'String', values: [{ v: 'Latest comments' }] },
            { name: 'size', type: 'Long', values: [{ v: 5 }] },
        ]);
    });

    it('should leave the config untouched when the descriptor cannot be loaded', async () => {
        const params = await savePage(customizedPage(latestCommentsPart(UNKNOWN_PART_KEY)));

        expect(partConfig(params)).toEqual([
            { name: 'headline', type: 'String', values: [{ v: 'Latest comments' }] },
            { name: 'size', type: 'String', values: [{ v: '5' }] },
        ]);
    });
});

describe('updateWizardContent', () => {
    const sent: string[] = [];
    const saved = (label: string, content: Content) => () => {
        sent.push(label);
        return Q(content);
    };

    const edited = (change: (builder: ContentBuilder) => void): Content => {
        const builder = createContent(null).newBuilder();
        change(builder);
        return builder.build();
    };

    let persisted: Content;
    let updated: Content;
    let withPage: Content;
    let ready: Content;

    beforeEach(() => {
        sent.length = 0;
        persisted = createContent(null);
        updated = edited((builder) => builder.setDisplayName('Updated'));
        withPage = edited((builder) => builder.setDisplayName('With page'));
        ready = edited((builder) => builder.setDisplayName('Ready'));
        $wizardDraftWorkflowState.set(null);

        vi.spyOn(UpdateContentRequest.prototype, 'sendAndParse').mockImplementation(saved('content', updated));
        vi.spyOn(CreatePageRequest.prototype, 'sendAndParse').mockImplementation(saved('page', withPage));
        vi.spyOn(UpdateWorkflowRequest.prototype, 'sendAndParse').mockImplementation(saved('workflow', ready));
        vi.spyOn(GetComponentDescriptorRequest.prototype, 'sendAndParse').mockImplementation(() =>
            Q.reject<Descriptor>(new Error('No descriptor')),
        );
    });

    afterEach(() => {
        vi.restoreAllMocks();
        $wizardDraftWorkflowState.set(null);
    });

    it('should send nothing when the drafts match the persisted content', async () => {
        viewed.content = createContent(null);

        const result = await updateWizardContent(persisted);

        expect(sent).toEqual([]);
        expect(result).toEqual({ content: persisted, dataUpdated: false, pageUpdated: false, workflowUpdated: false });
    });

    it('should send a rename without reporting the data as updated', async () => {
        viewed.content = edited((builder) => builder.setName(new ContentName('renamed')));

        const result = await updateWizardContent(persisted);

        expect(sent).toEqual(['content']);
        expect(result).toEqual({ content: updated, dataUpdated: false, pageUpdated: true, workflowUpdated: false });
    });

    it('should send changed data', async () => {
        const data = new PropertyTree();
        data.setString('title', 0, 'Changed');
        viewed.content = edited((builder) => builder.setData(data));

        const result = await updateWizardContent(persisted);

        expect(sent).toEqual(['content']);
        expect(result.dataUpdated).toBe(true);
    });

    it('should send the content, then the page, then the workflow', async () => {
        viewed.content = edited((builder) => {
            builder.setDisplayName('Changed');
            builder.setPage(customizedPage(latestCommentsPart()));
        });
        $wizardDraftWorkflowState.set(WorkflowState.READY);

        const result = await updateWizardContent(persisted);

        expect(sent).toEqual(['content', 'page', 'workflow']);
        expect(result).toEqual({ content: ready, dataUpdated: false, pageUpdated: true, workflowUpdated: true });
    });

    it('should send only the page when nothing else changed', async () => {
        viewed.content = edited((builder) => builder.setPage(customizedPage(latestCommentsPart())));

        const result = await updateWizardContent(persisted);

        expect(sent).toEqual(['page']);
        expect(result.content).toBe(withPage);
    });
});

describe('resolveSavedMessage', () => {
    const content = (change: (builder: ContentBuilder) => void = () => undefined): Content => {
        const builder = createContent(null).newBuilder();
        change(builder);
        return builder.build();
    };
    const plain = { wasInherited: false, renamed: false };

    it('should say what the save did', () => {
        const readyContent = content((builder) =>
            builder.setWorkflow(Workflow.create().setState(WorkflowState.READY).build()),
        );

        expect(resolveSavedMessage(content(), plain)).toBe('notify.item.saved post');
        expect(resolveSavedMessage(readyContent, plain)).toBe('notify.item.markedAsReady post');
        expect(resolveSavedMessage(readyContent, { ...plain, renamed: true })).toBe(
            'notify.wizard.contentRenamed post',
        );
    });

    it('should put localizing and unnamed content first', () => {
        const unnamed = content((builder) => builder.setName(ContentUnnamed.newUnnamed()));

        expect(resolveSavedMessage(unnamed, { wasInherited: false, renamed: true })).toBe('notify.item.savedUnnamed');
        expect(resolveSavedMessage(unnamed, { wasInherited: true, renamed: true })).toBe('notify.content.localized');
    });
});
